export interface SeriesInput extends TaskInput {
  recurrence: Recurrence
  endDate?: ISODate | null
}

export async function createSeries(input: SeriesInput): Promise<TaskSeries> {
  const now = nowISO()
  const series: TaskSeries = {
    id: uid(),
    title: input.title.trim(),
    description: input.description?.trim() || undefined,
    priority: input.priority ?? 'normal',
    category: input.category?.trim() || undefined,
    tags: input.tags ?? [],
    dueTime: input.dueTime || null,
    recurrence: input.recurrence,
    startDate: input.date,
    endDate: input.endDate ?? null,
    exceptions: [],
    materializedThrough: null,
    createdAt: now,
    updatedAt: now,
  }
  await db.taskSeries.add(series)
  await materializeSeries(defaultHorizon(input.date))
  return series
}

function defaultHorizon(atLeast?: ISODate): ISODate {
  const h = addDays(today(), DEFAULT_HORIZON_DAYS)
  return atLeast && atLeast > h ? atLeast : h
}

/** Pure: the occurrence dates a series should have between `from` and `to`. */
export function seriesDatesBetween(series: TaskSeries, from: ISODate, to: ISODate): ISODate[] {
  const out: ISODate[] = []
  let d = from < series.startDate ? series.startDate : from
  const end = series.endDate && series.endDate < to ? series.endDate : to
  let guard = 0
  while (d <= end && guard++ < 2000) {
    if (!series.exceptions.includes(d) && occursOn(series.recurrence, series.startDate, d, series.endDate)) out.push(d)
    d = addDays(d, 1)
  }
  return out
}

/**
 * Generate missing occurrences for every series up to `upTo` (inclusive).
 * Idempotent and safe to call often: it checks [seriesId+date] inside a transaction.
 */
export async function materializeSeries(upTo: ISODate = defaultHorizon()): Promise<number> {
  let created = 0
  await db.transaction('rw', db.tasks, db.taskSeries, async () => {
    const all = await db.taskSeries.toArray()
    for (const s of all) {
      if (s.materializedThrough && s.materializedThrough >= upTo) continue
      const from = s.materializedThrough ? addDays(s.materializedThrough, 1) : s.startDate
      const dates = seriesDatesBetween(s, from, upTo)
      for (const date of dates) {
        const exists = await db.tasks.where('[seriesId+date]').equals([s.id, date]).count()
        if (exists) continue
        const now = nowISO()
        const order = (await db.tasks.where('date').equals(date).count()) + 0
        await db.tasks.add({
          id: uid(),
          title: s.title,
          description: s.description,
          date,
          dueTime: s.dueTime ?? null,
          completed: false,
          completedAt: null,
          priority: s.priority,
          category: s.category,
          tags: s.tags,
          seriesId: s.id,
          order,
          createdAt: now,
          updatedAt: now,
        })
        created++
      }
      await db.taskSeries.update(s.id, { materializedThrough: upTo })
    }
  })
  return created
}

/**
 * Edit a whole series from `fromDate` onwards. Metadata changes are applied to
 * future, incomplete, non-detached occurrences. A recurrence change splits the
 * series: the old one ends the day before, a new one starts on `fromDate`.
 */
export async function updateSeries(
  seriesId: string,
  patch: Partial<Pick<TaskSeries, 'title' | 'description' | 'priority' | 'category' | 'tags' | 'dueTime' | 'recurrence' | 'endDate'>>,
  fromDate: ISODate,
): Promise<void> {
  const s = await db.taskSeries.get(seriesId)
  if (!s) return
  const recurrenceChanged = patch.recurrence && JSON.stringify(patch.recurrence) !== JSON.stringify(s.recurrence)

  if (recurrenceChanged) {
    await db.transaction('rw', db.tasks, db.taskSeries, async () => {
      // Remove future incomplete generated occurrences of the old rule.
      const future = await db.tasks.where('seriesId').equals(seriesId).filter((t) => t.date >= fromDate && !t.completed && !t.detached).toArray()
      await db.tasks.bulkDelete(future.map((t) => t.id))
      if (fromDate <= s.startDate) {
        await db.taskSeries.update(seriesId, { ...patch, materializedThrough: addDays(fromDate, -1), updatedAt: nowISO() })
      } else {
        await db.taskSeries.update(seriesId, { endDate: addDays(fromDate, -1), updatedAt: nowISO() })
        const now = nowISO()
        await db.taskSeries.add({
          ...s,
          ...patch,
          id: uid(),
          startDate: fromDate,
          exceptions: [],
          materializedThrough: null,
          createdAt: now,
          updatedAt: now,
        })
      }
    })
    await materializeSeries(defaultHorizon(fromDate))
    return
  }

  await db.transaction('rw', db.tasks, db.taskSeries, async () => {
    await db.taskSeries.update(seriesId, { ...patch, updatedAt: nowISO() })
    const future = await db.tasks.where('seriesId').equals(seriesId).filter((t) => t.date >= fromDate && !t.completed && !t.detached).toArray()
    const fields: Partial<Task> = {}
    if (patch.title !== undefined) fields.title = patch.title
    if (patch.description !== undefined) fields.description = patch.description
    if (patch.priority !== undefined) fields.priority = patch.priority
    if (patch.category !== undefined) fields.category = patch.category
    if (patch.tags !== undefined) fields.tags = patch.tags
    if (patch.dueTime !== undefined) fields.dueTime = patch.dueTime
    await Promise.all(future.map((t) => db.tasks.update(t.id, { ...fields, updatedAt: nowISO() })))
    if (patch.endDate) {
      const beyond = await db.tasks.where('seriesId').equals(seriesId).filter((t) => t.date > patch.endDate! && !t.completed).toArray()
      await db.tasks.bulkDelete(beyond.map((t) => t.id))
    }
  })
}

/**
 * Stop a series from `fromDate`. Incomplete occurrences on/after that date are
 * removed; completed history is kept.
 */
export async function deleteSeries(seriesId: string, fromDate: ISODate): Promise<void> {
  const s = await db.taskSeries.get(seriesId)
  if (!s) return
  const removed = await db.tasks.where('seriesId').equals(seriesId).filter((t) => t.date >= fromDate && !t.completed).toArray()
  await db.transaction('rw', db.tasks, db.taskSeries, async () => {
    await db.tasks.bulkDelete(removed.map((t) => t.id))
    if (fromDate <= s.startDate) await db.taskSeries.delete(seriesId)
    else await db.taskSeries.update(seriesId, { endDate: addDays(fromDate, -1), updatedAt: nowISO() })
  })
  undoToast('Repeating task stopped', async () => {
    await db.transaction('rw', db.tasks, db.taskSeries, async () => {
      await db.taskSeries.put(s)
      await db.tasks.bulkPut(removed)
    })
  })
}

