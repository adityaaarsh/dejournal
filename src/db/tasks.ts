import { db } from './db'
import type { ISODate, Priority, Recurrence, Task, TaskSeries } from './types'
import { addDays, today } from '@/lib/dates'
import { nowISO, uid } from '@/lib/id'
import { occursOn } from '@/lib/recurrence'
import { undoToast } from '@/stores/ui'

/**
 * Tasks.
 *
 * Recurring tasks are stored as a TaskSeries (the rule) plus one Task row per
 * occurrence (`seriesId` + `date`). Occurrences are "materialized" up to a
 * horizon date so each has its own completion state, history and edits.
 * Deleting a single occurrence records an exception so it is not regenerated.
 */

export interface TaskInput {
  title: string
  description?: string
  date: ISODate
  dueTime?: string | null
  priority?: Priority
  category?: string
  tags?: string[]
}

/** How far ahead of today occurrences are generated by default. */
export const DEFAULT_HORIZON_DAYS = 14

async function nextOrder(date: ISODate): Promise<number> {
  const last = await db.tasks.where('date').equals(date).toArray()
  return last.reduce((m, t) => Math.max(m, t.order), -1) + 1
}

export async function createTask(input: TaskInput): Promise<Task> {
  const now = nowISO()
  const task: Task = {
    id: uid(),
    title: input.title.trim(),
    description: input.description?.trim() || undefined,
    date: input.date,
    dueTime: input.dueTime || null,
    completed: false,
    completedAt: null,
    priority: input.priority ?? 'normal',
    category: input.category?.trim() || undefined,
    tags: input.tags ?? [],
    seriesId: null,
    order: await nextOrder(input.date),
    createdAt: now,
    updatedAt: now,
  }
  await db.tasks.add(task)
  return task
}

/** Update one task. Editing an occurrence detaches it from future series edits. */
export async function updateTask(id: string, patch: Partial<Task>): Promise<void> {
  const task = await db.tasks.get(id)
  if (!task) return
  const changes: Partial<Task> = { ...patch, updatedAt: nowISO() }
  if (task.seriesId && ('title' in patch || 'dueTime' in patch || 'priority' in patch || 'description' in patch)) {
    changes.detached = true
  }
  if (patch.date && patch.date !== task.date) changes.order = await nextOrder(patch.date)
  await db.tasks.update(id, changes)
}

export async function setTaskCompleted(id: string, completed: boolean): Promise<void> {
  await db.tasks.update(id, { completed, completedAt: completed ? nowISO() : null, updatedAt: nowISO() })
}

export async function toggleTask(id: string): Promise<void> {
  const t = await db.tasks.get(id)
  if (t) await setTaskCompleted(id, !t.completed)
}

/** Move a task to another date (e.g. carry an overdue task forward). */
export async function moveTask(id: string, date: ISODate): Promise<void> {
  const t = await db.tasks.get(id)
  if (!t || t.date === date) return
  await db.tasks.update(id, {
    date,
    movedFrom: t.movedFrom ?? t.date,
    order: await nextOrder(date),
    detached: t.seriesId ? true : t.detached,
    updatedAt: nowISO(),
  })
}

/** Persist a new manual order for tasks on one date. */
export async function reorderTasks(orderedIds: string[]): Promise<void> {
  await db.transaction('rw', db.tasks, async () => {
    await Promise.all(orderedIds.map((id, i) => db.tasks.update(id, { order: i })))
  })
}

/** Delete one task (or one occurrence of a series) with Undo. */
export async function deleteTask(id: string): Promise<void> {
  const task = await db.tasks.get(id)
  if (!task) return
  let series: TaskSeries | undefined
  await db.transaction('rw', db.tasks, db.taskSeries, async () => {
    await db.tasks.delete(id)
    if (task.seriesId) {
      series = await db.taskSeries.get(task.seriesId)
      if (series && !series.exceptions.includes(task.date)) {
        await db.taskSeries.update(series.id, { exceptions: [...series.exceptions, task.date] })
      }
    }
  })
  undoToast('Task deleted', async () => {
    await db.transaction('rw', db.tasks, db.taskSeries, async () => {
      await db.tasks.put(task)
      if (series) await db.taskSeries.put(series)
    })
  })
}

