const PRIORITY_RANK: Record<Priority, number> = { high: 0, normal: 1, low: 2 }

/** Incomplete first, then manual order. */
export function sortTasks(tasks: Task[]): Task[] {
  return tasks.slice().sort((a, b) => {
    if (a.completed !== b.completed) return a.completed ? 1 : -1
    if (a.order !== b.order) return a.order - b.order
    return a.createdAt.localeCompare(b.createdAt)
  })
}

export function sortByPriority(tasks: Task[]): Task[] {
  return tasks.slice().sort((a, b) => PRIORITY_RANK[a.priority] - PRIORITY_RANK[b.priority] || a.order - b.order)
}

export function isOverdue(task: Task, ref: ISODate = today()): boolean {
  return !task.completed && task.date < ref
}
